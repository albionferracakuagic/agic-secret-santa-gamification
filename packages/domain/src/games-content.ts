export type L10n = { en: string; it: string };

export interface TriviaQuestion {
  id: string;
  prompt: L10n;
  options: L10n[];
  /** Index of the correct option in `options`. */
  correct: number;
}

/** [en, it] pair, or one string when both languages share it (names, numbers). */
const o = (en: string, it: string = en): L10n => ({ en, it });
const q = (
  id: string,
  en: string,
  it: string,
  options: L10n[],
  correct: number,
): TriviaQuestion => ({ id, prompt: { en, it }, options, correct });

